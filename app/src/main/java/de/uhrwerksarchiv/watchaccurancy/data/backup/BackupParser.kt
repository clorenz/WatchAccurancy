package de.uhrwerksarchiv.watchaccurancy.data.backup

import de.uhrwerksarchiv.watchaccurancy.data.model.MeasurementLog
import de.uhrwerksarchiv.watchaccurancy.data.model.Watch
import de.uhrwerksarchiv.watchaccurancy.data.model.WatchPosition
import java.util.Locale

data class ParseReport(
    val watches: List<Watch>,
    val logs: List<MeasurementLog>,
    val warnings: List<String>,
    val errors: List<String>,
    val isValid: Boolean
)

object BackupParser {

    private const val PREFIX_WATCH = "WATCH:"
    private const val PREFIX_LOG = "LOG:"

    private const val MIN_VALID_TIMESTAMP = 946684800000L      // ~ Year 2000
    private const val MAX_VALID_TIMESTAMP = 4102444800000L     // ~ Year 2100

    fun parse(content: String): ParseReport {
        val watches = mutableListOf<Watch>()
        val logs = mutableListOf<MeasurementLog>()
        val warnings = mutableListOf<String>()
        val errors = mutableListOf<String>()

        // Remove possible UTF-8 BOM
        val cleanContent = content.removePrefix("\uFEFF").trim()
        val lines = cleanContent.lines()
        var lineIndex = 0

        for (rawLine in lines) {
            lineIndex++
            val line = rawLine.trim()
            if (line.isEmpty() || line.startsWith("#") || line.startsWith("//")) {
                continue
            }

            // WatchCheck / WatchCheck2 header line
            if (line.startsWith("WatchCheck", ignoreCase = true)) {
                // Authentic WatchCheck header line - perfectly valid, no warning needed
                continue
            }

            if (line.startsWith(PREFIX_WATCH, ignoreCase = true)) {
                parseWatchLine(line, lineIndex, watches, warnings, errors)
            } else if (line.startsWith(PREFIX_LOG, ignoreCase = true)) {
                parseLogLine(line, lineIndex, logs, warnings, errors)
            } else {
                warnings.add("Zeile $lineIndex ignoriert (unbekanntes Präfix): \"$line\"")
            }
        }

        val watchIds = watches.map { it.id }.toSet()
        val missingWatchIds = logs.map { it.watchId }.filter { it !in watchIds }.distinct()

        val autoGeneratedWatches = mutableListOf<Watch>()
        for (missingId in missingWatchIds) {
            warnings.add("WatchID $missingId in Logs vorhanden, aber kein passender WATCH-Eintrag. Platzhalter wird erstellt.")
            autoGeneratedWatches.add(
                Watch(
                    id = missingId,
                    model = "Importierte Uhr #$missingId",
                    serialNumber = "",
                    caliber = "",
                    notes = "Automatisch bei Import generiert",
                    createdAt = System.currentTimeMillis()
                )
            )
        }

        val allWatches = (watches + autoGeneratedWatches).distinctBy { it.id }

        return ParseReport(
            watches = allWatches,
            logs = logs,
            warnings = warnings,
            errors = errors,
            isValid = errors.isEmpty() && (allWatches.isNotEmpty() || logs.isNotEmpty())
        )
    }

    private fun parseWatchLine(
        line: String,
        lineIndex: Int,
        outWatches: MutableList<Watch>,
        outWarnings: MutableList<String>,
        outErrors: MutableList<String>
    ) {
        val payload = line.substringAfter(PREFIX_WATCH).trim()
        val tokens = payload.split('|').map { it.trim() }

        // WatchCheck format: id|name|serial|createdAt|comment
        if (tokens.size < 2) {
            outErrors.add("Zeile $lineIndex: Ungültiges WATCH-Format (zu wenige Spalten: ${tokens.size}). Erwartet mindestens ID und Modell.")
            return
        }

        val idStr = tokens[0]
        val model = tokens[1]
        val rawSerial = tokens.getOrElse(2) { "" }
        val rawCreated = tokens.getOrElse(3) { "" }
        val rawNotes = tokens.getOrElse(4) { "" }

        val watchId = idStr.toLongOrNull()
        if (watchId == null || watchId <= 0) {
            outErrors.add("Zeile $lineIndex: Ungültige WatchID '$idStr'. Muss eine positive Zahl sein.")
            return
        }

        val serialNumber = if (rawSerial.equals("null", ignoreCase = true)) "" else rawSerial
        val notes = if (rawNotes.equals("null", ignoreCase = true)) "" else rawNotes

        var createdAt = rawCreated.toLongOrNull() ?: 0L
        if (createdAt < MIN_VALID_TIMESTAMP || createdAt > MAX_VALID_TIMESTAMP) {
            if (rawCreated.isNotEmpty() && !rawCreated.equals("null", ignoreCase = true) && rawCreated != "0") {
                outWarnings.add("Zeile $lineIndex: Zeitstempel $createdAt für Uhr '$model' unplausibel, wird auf aktuellen Zeitpunkt gesetzt.")
            }
            createdAt = System.currentTimeMillis()
        }

        val finalModel = model.ifBlank { "Uhr #$watchId" }

        outWatches.add(
            Watch(
                id = watchId,
                model = finalModel,
                serialNumber = serialNumber,
                caliber = "",
                notes = notes,
                createdAt = createdAt
            )
        )
    }

    private fun parseLogLine(
        line: String,
        lineIndex: Int,
        outLogs: MutableList<MeasurementLog>,
        outWarnings: MutableList<String>,
        outErrors: MutableList<String>
    ) {
        val payload = line.substringAfter(PREFIX_LOG).trim()
        val tokens = payload.split('|').map { it.trim() }

        // WatchCheck format: id|watchId|period|refTime|watchTime|position|temperature|comment
        if (tokens.size < 5) {
            outErrors.add("Zeile $lineIndex: Ungültiges LOG-Format (nur ${tokens.size} Spalten). Erwartet mind. 5 Tokens.")
            return
        }

        val logIdStr = tokens[0]
        val watchIdStr = tokens[1]
        val setIdStr = tokens.getOrElse(2) { "0" }
        val ntpTimeStr = tokens.getOrElse(3) { "" }
        val watchTimeStr = tokens.getOrElse(4) { "" }
        val positionCode = tokens.getOrElse(5) { "WORN" }
        val extraValueStr = tokens.getOrElse(6) { "0" }
        val rawNote = tokens.getOrElse(7) { "" }

        val logId = logIdStr.toLongOrNull()
        val watchId = watchIdStr.toLongOrNull()

        if (logId == null || logId <= 0) {
            outErrors.add("Zeile $lineIndex: Ungültige LogID '$logIdStr'.")
            return
        }
        if (watchId == null || watchId <= 0) {
            outErrors.add("Zeile $lineIndex: Ungültige WatchID '$watchIdStr'.")
            return
        }

        val setId = setIdStr.toIntOrNull() ?: 0

        val ntpTime = ntpTimeStr.toLongOrNull()
        val watchTime = watchTimeStr.toLongOrNull()

        if (ntpTime == null || ntpTime < MIN_VALID_TIMESTAMP || ntpTime > MAX_VALID_TIMESTAMP) {
            outErrors.add("Zeile $lineIndex: Unplausibler NTP-Zeitstempel '$ntpTimeStr'.")
            return
        }
        if (watchTime == null || watchTime < MIN_VALID_TIMESTAMP || watchTime > MAX_VALID_TIMESTAMP) {
            outErrors.add("Zeile $lineIndex: Unplausibler Uhr-Zeitstempel '$watchTimeStr'.")
            return
        }

        val cleanPosCode = if (positionCode.isBlank() || positionCode.equals("null", ignoreCase = true)) {
            "WORN"
        } else {
            WatchPosition.fromCode(positionCode).code
        }

        // In WatchCheck, unset temperature is stored as -273 or -273.15 or null
        val extraValue = if (extraValueStr.equals("null", ignoreCase = true) ||
            extraValueStr.startsWith("-273")
        ) {
            0.0
        } else {
            extraValueStr.toDoubleOrNull() ?: 0.0
        }

        val notes = if (rawNote.equals("null", ignoreCase = true)) "" else rawNote

        outLogs.add(
            MeasurementLog(
                id = logId,
                watchId = watchId,
                setId = setId,
                ntpTimestampMs = ntpTime,
                watchTimestampMs = watchTime,
                positionCode = cleanPosCode,
                extraValue = extraValue,
                notes = notes
            )
        )
    }

    fun exportToFormat(watches: List<Watch>, logs: List<MeasurementLog>): String {
        val sb = StringBuilder()
        // Header line matching authentic WatchCheck / WatchCheck2 format
        sb.append("WatchCheck2\n")
        sb.append("# WatchAccurancy / WatchCheck Backup Export\n")
        sb.append("# Format: GPLv3 Open Source Compatible\n\n")

        for (watch in watches) {
            sb.append("WATCH: ")
                .append(watch.id).append('|')
                .append(watch.model).append('|')
                .append(watch.serialNumber).append('|')
                .append(watch.createdAt).append('|')
                .append(watch.notes).append("\n")
        }

        sb.append("\n")

        val sortedLogs = logs.sortedWith(compareBy({ it.watchId }, { it.ntpTimestampMs }))
        for (log in sortedLogs) {
            val extraFormatted = if (log.extraValue % 1.0 == 0.0) {
                log.extraValue.toLong().toString()
            } else {
                String.format(Locale.US, "%.1f", log.extraValue)
            }

            sb.append("LOG: ")
                .append(log.id).append('|')
                .append(log.watchId).append('|')
                .append(log.setId).append('|')
                .append(log.ntpTimestampMs).append('|')
                .append(log.watchTimestampMs).append('|')
                .append(log.positionCode).append('|')
                .append(extraFormatted).append('|')
                .append(log.notes).append("\n")
        }

        return sb.toString()
    }

